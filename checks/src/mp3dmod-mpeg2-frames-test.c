static HRESULT write_tone(WCHAR *path)
{
    WCHAR folder[MAX_PATH];
    DWORD written = 0;
    HANDLE file;

    if (!GetTempPathW(MAX_PATH, folder) || !GetTempFileNameW(folder, L"mp3", 0, path)) return HRESULT_FROM_WIN32(GetLastError());
    lstrcatW(path, L".mp3");
    file = CreateFileW(path, GENERIC_WRITE, 0, NULL, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, NULL);
    if (file == INVALID_HANDLE_VALUE) return HRESULT_FROM_WIN32(GetLastError());
    WriteFile(file, tone, sizeof(tone), &written, NULL);
    CloseHandle(file);
    return written == sizeof(tone) ? S_OK : E_FAIL;
}

static HRESULT open_reader(const WCHAR *path, IMFSourceReader **reader)
{
    IMFMediaType *type = NULL;
    HRESULT hr;

    if (FAILED(hr = MFCreateSourceReaderFromURL(path, NULL, reader))) return hr;
    if (SUCCEEDED(hr = MFCreateMediaType(&type)))
    {
        IMFMediaType_SetGUID(type, &MF_MT_MAJOR_TYPE, &MFMediaType_Audio);
        IMFMediaType_SetGUID(type, &MF_MT_SUBTYPE, &MFAudioFormat_PCM);
        hr = IMFSourceReader_SetCurrentMediaType(*reader, MF_SOURCE_READER_FIRST_AUDIO_STREAM, NULL, type);
        IMFMediaType_Release(type);
    }
    return hr;
}

static HRESULT count_samples(IMFSourceReader *reader, UINT32 *rate, UINT32 *block, LONGLONG *bytes)
{
    IMFMediaType *type;
    IMFMediaBuffer *buffer;
    IMFSample *sample;
    DWORD flags, length;
    HRESULT hr;

    if (FAILED(hr = IMFSourceReader_GetCurrentMediaType(reader, MF_SOURCE_READER_FIRST_AUDIO_STREAM, &type))) return hr;
    IMFMediaType_GetUINT32(type, &MF_MT_AUDIO_SAMPLES_PER_SECOND, rate);
    IMFMediaType_GetUINT32(type, &MF_MT_AUDIO_BLOCK_ALIGNMENT, block);
    IMFMediaType_Release(type);
    if (!*block) return E_UNEXPECTED;

    *bytes = 0;
    for (;;)
    {
        sample = NULL;
        flags = 0;
        hr = IMFSourceReader_ReadSample(reader, MF_SOURCE_READER_FIRST_AUDIO_STREAM, 0, NULL, &flags, NULL, &sample);
        if (FAILED(hr)) return hr;
        if (sample)
        {
            if (SUCCEEDED(IMFSample_ConvertToContiguousBuffer(sample, &buffer)))
            {
                if (SUCCEEDED(IMFMediaBuffer_GetCurrentLength(buffer, &length))) *bytes += length;
                IMFMediaBuffer_Release(buffer);
            }
            IMFSample_Release(sample);
        }
        if (flags & MF_SOURCE_READERF_ENDOFSTREAM) return S_OK;
    }
}

